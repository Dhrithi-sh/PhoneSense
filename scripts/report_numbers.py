"""Generate the report's numbers and tables from results/ (no hand-typed numbers).

    python scripts/report_numbers.py          # = make report-numbers

Writes ``report/generated/``:

* ``dataset_stats.tex``    data_stats.json (+ handcheck_summary.json if scored)
* ``index_stats.tex``      index_stats.json (vocabulary, postings, compressed vs. plain size)
* ``efficiency.tex``       latency_*.json (TF-IDF, BM25 query latency) + efficiency.json
                           (Boolean AND with vs. without skip pointers)
* ``bm25_tuning.tex``      bm25_tuning.json (best k1/b, BM25F weights, dev default vs. tuned)
* ``filters_subset.tex``   filters_subset_test.json (else _dev)
* ``numbers.tex``          ``\\newcommand`` macros for headline numbers, each with its source
* ``experiments_retrieval_skeleton.md``  outline of the retrieval experiments section with
                           facts (no interpretation) pulled from the results

Anything whose source file doesn't exist yet is written as ``pending``. Also refreshes the
README results summary (between the ``BEGIN/END results-summary`` markers) from
results/ablation_test.md, unless ``--no-readme``.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from phonesense.config import get_path, repo_root

PENDING = r"\textit{pending}"


def load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def esc(s: Any) -> str:
    s = str(s)
    for a, b in (
        ("\\", r"\textbackslash{}"),
        ("_", r"\_"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("#", r"\#"),
        ("$", r"\$"),
    ):
        s = s.replace(a, b)
    return s


def num(x: Any, fmt: str = "{:,}") -> str:
    return PENDING if x is None else esc(fmt.format(x))


def table(caption: str, label: str, head: list[str], rows: list[list[str]], src: str) -> str:
    cols = "l" + "r" * (len(head) - 1)
    out = [
        f"% generated by scripts/report_numbers.py from {src}",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        rf"\begin{{tabular}}{{{cols}}}",
        r"\toprule",
        " & ".join(head) + r" \\",
        r"\midrule",
    ]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += [
        r"\bottomrule",
        r"\end{tabular}",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\end{table}",
    ]
    return "\n".join(out) + "\n"


