def dataset_stats(res: Path) -> str:
    d = load(res / "data_stats.json") or {}
    hc = load(res / "handcheck_summary.json")
    rows = [
        ["Raw items (Cell Phones \\& Accessories)", num(d.get("raw_items"))],
        ["Phone candidates after rule filter", num(d.get("phone_candidates"))],
        ["Duplicate listings merged", num(d.get("duplicate_listings_merged"))],
        ["Phones kept ($\\geq$ 5 reviews)", num(d.get("kept_phones"))],
        ["Reviews kept", num(d.get("reviews_kept"))],
        ["Unique reviewers", num(d.get("unique_reviewers"))],
        ["Reviewers with $\\geq$ 2 phones", num(d.get("reviewers_with_2plus_phones"))],
        ["Brands", num(d.get("brand_count"))],
        ["Price known (\\%)", num(d.get("price_coverage_pct"), "{:.1f}")],
    ]
    for f, v in (d.get("spec_coverage_pct") or {}).items():
        rows.append([f"Spec coverage: \\texttt{{{esc(f)}}} (\\%)", num(v, "{:.1f}")])
    if hc:
        acc = (hc.get("spec_accuracy_overall") or {}).get("accuracy")
        rows += [
            ["Hand check: spec accuracy (\\%)", num(None if acc is None else 100 * acc, "{:.1f}")],
            [
                "Hand check: filter precision (\\%)",
                num(
                    None
                    if hc.get("filter_precision_kept_sample") is None
                    else 100 * hc["filter_precision_kept_sample"],
                    "{:.1f}",
                ),
            ],
        ]
    else:
        rows += [
            ["Hand check: spec accuracy (\\%)", PENDING],
            ["Hand check: filter precision (\\%)", PENDING],
        ]
    return table(
        "Dataset after the T02 pipeline (Amazon Reviews 2023, Cell Phones \\& Accessories).",
        "tab:dataset",
        ["Quantity", "Value"],
        rows,
        "results/data_stats.json, results/handcheck_summary.json",
    )


def index_stats(res: Path) -> str:
    s = load(res / "index_stats.json") or {}
    vs, tp, al = s.get("vocab_size", {}), s.get("total_postings", {}), s.get("avg_doc_len", {})
    rows = [
        [esc(f), num(vs.get(f)), num(tp.get(f)), num(al.get(f), "{:.1f}")]
        for f in ("title", "features", "description", "text")
    ]
    sz = s.get("size_bytes", {})
    vb, raw = sz.get("vbyte", {}), sz.get("uncompressed_uint32", {})

    def mb(b):
        return None if b is None else b / 2**20

    rows += [
        [r"\midrule Postings size, VB (MB)", num(mb(vb.get("postings")), "{:.1f}"), "", ""],
        ["Postings size, uint32 (MB)", num(mb(raw.get("postings")), "{:.1f}"), "", ""],
        ["Compression ratio", num(s.get("postings_compression_ratio"), "{:.2f}x"), "", ""],
        [
            "Build / load time (s)",
            num(s.get("build_seconds"), "{:.1f}") + " / " + num(s.get("load_seconds"), "{:.1f}"),
            "",
            "",
        ],
    ]
    return table(
        f"Inverted index over N = {num(s.get('N'))} phones.",
        "tab:index",
        ["Field", "Vocabulary", "Postings", "Avg.\\ length"],
        rows,
        "results/index_stats.json",
    )


def efficiency(res: Path) -> str:
    rows = []
    for p in sorted(res.glob("latency_*.json")):
        d = load(p)
        rows.append(
            [
                esc(d["run"]),
                num(d["mean_ms"], "{:.2f}"),
                num(d["p95_ms"], "{:.2f}"),
                num(d.get("queries")),
            ]
        )
    if not rows:
        rows.append(["TF-IDF / BM25 runs", PENDING, PENDING, PENDING])
    b = (load(res / "efficiency.json") or {}).get("boolean_and")
    if b:
        for mode in ("with_skips", "without_skips"):
            m = b[mode]
            rows.append(
                [
                    f"Boolean AND, {mode.replace('_', ' ')}",
                    num(m["mean_us"] / 1000, "{:.3f}"),
                    num(m["p95_us"] / 1000, "{:.3f}"),
                    num(b["n_queries"]),
                ]
            )
        rows.append(
            [
                f"Skip pointers: comparisons $-${esc(round(100 * b['comparison_reduction']))}"
                f"\\%, speed-up {esc(b['speedup_mean_latency'])}x",
                "",
                "",
                "",
            ]
        )
    else:
        rows.append(["Boolean AND", PENDING, PENDING, PENDING])
    return table(
        "Query latency (ms, single thread, pure Python).",
        "tab:efficiency",
        ["System", "Mean", "p95", "Queries"],
        rows,
        "results/latency_*.json, results/efficiency.json",
    )


def bm25_tuning(res: Path) -> str:
    t = load(res / "bm25_tuning.json")
    if not t:
        return table(
            "BM25 tuning on dev.",
            "tab:bm25-tuning",
            ["Setting", "Value"],
            [["Tuning", PENDING]],
            "results/bm25_tuning.json",
        )
    obj = t["objective"]
    f = t["bm25f"]["best"]
    rows = [
        [
            f"BM25 default (k1 = 1.2, b = 0.75), dev {esc(obj)}",
            num((t.get("default") or {}).get(obj), "{:.3f}"),
        ],
        [
            f"BM25 tuned (k1 = {t['best']['k1']:g}, b = {t['best']['b']:g}), dev {esc(obj)}",
            num(t["best"][obj], "{:.3f}"),
        ],
        [
            f"BM25F weights title / features / description = {f['title']:g} / "
            f"{f['features']:g} / {f['description']:g}, dev {esc(obj)}",
            num(f[obj], "{:.3f}"),
        ],
        [
            "Grid",
            esc(
                f"{len(t['grid'])} (k1, b) + {len(t['bm25f']['grid'])} weight settings, "
                f"{t['n_queries']} dev queries"
            ),
        ],
    ]
    return table(
        "BM25 / BM25F tuning (dev only).",
        "tab:bm25-tuning",
        ["Setting", "Value"],
        rows,
        "results/bm25_tuning.json",
    )


def filters_subset(res: Path) -> str:
    d = load(res / "filters_subset_test.json") or load(res / "filters_subset_dev.json")
    if not d:
        return table(
            "Queries with vs. without constraints.",
            "tab:filters-subset",
            ["Run", "Subset", "n", "nDCG@10"],
            [["", PENDING, "", ""]],
            "results/filters_subset_<split>.json",
        )
    rows = []
    for run, r in d["runs"].items():
        for lab, s in r.items():
            p = s.get("p_nDCG@10_vs_base")
            rows.append(
                [
                    esc(run),
                    lab.replace("_", " "),
                    num(s["n"]),
                    num(s["nDCG@10"], "{:.3f}"),
                    num(s["MAP"], "{:.3f}"),
                    "" if p is None else num(p, "{:.3f}"),
                ]
            )
    return table(
        f"Queries with vs.\\ without constraints ({esc(d.get('split'))} split). p: "
        "paired randomization test vs.\\ bm25\\_tuned on that subset.",
        "tab:filters-subset",
        ["Run", "Subset", "n", "nDCG@10", "MAP", "p"],
        rows,
        f"results/filters_subset_{d.get('split')}.json",
    )


def macros(res: Path) -> tuple[str, dict[str, Any]]:
    abl = load(res / "ablation.json") or {}
    facts: dict[str, Any] = {}

    def row(split: str, base: str) -> dict | None:
        return next(
            (
                r
                for r in (abl.get("rows") or {}).get(split, [])
                if r.get("run") == base and r.get("status") == "ok"
            ),
            None,
        )

    def m(split: str, base: str, metric: str = "nDCG@10") -> float | None:
        r = row(split, base)
        return r["metrics"][metric] if r else None

    best = (abl.get("best_overall") or {}).get("run")
    test_q = next(
        (
            r["n_queries"]
            for r in (abl.get("rows") or {}).get("test", [])
            if r.get("status") == "ok"
        ),
        None,
    )
    kappa = load(res / "kappa.json") or {}
    queries = get_path("queries")
    n_dev = n_test = None
    if queries.exists():
        from phonesense.io import read_queries

        qs = read_queries(queries)
        n_dev, n_test = sum(q.split == "dev" for q in qs), sum(q.split == "test" for q in qs)
    d = load(res / "data_stats.json") or {}
    e = (load(res / "efficiency.json") or {}).get("boolean_and") or {}
    vals = [
        ("numPhones", d.get("kept_phones"), "{:,}", "results/data_stats.json"),
        ("numReviews", d.get("reviews_kept"), "{:,}", "results/data_stats.json"),
        ("priceCoverage", d.get("price_coverage_pct"), "{:.1f}", "results/data_stats.json"),
        ("numQueriesDev", n_dev, "{}", "queries/queries.jsonl"),
        ("numQueriesTest", n_test, "{}", "queries/queries.jsonl"),
        ("numQueriesTestScored", test_q, "{}", "results/ablation.json"),
        ("tfidfNDCG", m("test", "tfidf_lnc.ltc"), "{:.3f}", "results/ablation.json"),
        ("bmDefaultNDCG", m("test", "bm25_default"), "{:.3f}", "results/ablation.json"),
        ("bmTunedNDCG", m("test", "bm25_tuned"), "{:.3f}", "results/ablation.json"),
        ("bmTunedMAP", m("test", "bm25_tuned", "MAP"), "{:.3f}", "results/ablation.json"),
        ("bestSystem", best, "{}", "results/ablation.json"),
        ("bestSystemNDCG", m("test", best) if best else None, "{:.3f}", "results/ablation.json"),
        ("bestSystemDevNDCG", m("dev", best) if best else None, "{:.3f}", "results/ablation.json"),
        (
            "bestVsBMDelta",
            (m("test", best) - m("test", "bm25_tuned"))
            if best and m("test", best) is not None and m("test", "bm25_tuned") is not None
            else None,
            "{:+.3f}",
            "results/ablation.json",
        ),
        ("kappaLLMHuman", kappa.get("kappa"), "{:.2f}", "results/kappa.json"),
        ("kappaWeighted", kappa.get("weighted_kappa"), "{:.2f}", "results/kappa.json"),
        ("skipSpeedup", e.get("speedup_mean_latency"), "{:.2f}", "results/efficiency.json"),
        (
            "skipComparisonCut",
            None if not e else 100 * e["comparison_reduction"],
            "{:.0f}",
            "results/efficiency.json",
        ),
    ]
    lines = ["% generated by scripts/report_numbers.py; do not edit by hand"]
    for name, v, fmt, src in vals:
        facts[name] = v
        lines.append(rf"\newcommand{{\{name}}}{{{num(v, fmt)}}}  % {src}")
    return "\n".join(lines) + "\n", facts


def skeleton(res: Path, facts: dict[str, Any]) -> str:
    abl = load(res / "ablation.json") or {}
    t = load(res / "bm25_tuning.json")
    sub = load(res / "filters_subset_test.json") or load(res / "filters_subset_dev.json")
    e = (load(res / "efficiency.json") or {}).get("boolean_and")

    def f(v: Any, fmt: str = "{:.3f}") -> str:
        return "pending" if v is None else fmt.format(v)

    L = [
        "# Experiments (retrieval): skeleton",
        "",
        "Facts only, generated by scripts/report_numbers.py. Write the prose around them.",
        "",
        "## Setup",
        "",
        f"- Collection: {f(facts['numPhones'], '{:,}')} phones, "
        f"{f(facts['numReviews'], '{:,}')} reviews (Table `tab:dataset`).",
        f"- Queries: {f(facts['numQueriesDev'], '{}')} dev, {f(facts['numQueriesTest'], '{}')} "
        "test; tuning on dev only, test evaluated once.",
        "- Relevance: graded 0-3, relevant = grade >= 2, unjudged = non-relevant; LLM judge "
        f"over pooled runs, human subset: kappa = {f(facts['kappaLLMHuman'], '{:.2f}')}, "
        f"weighted kappa = {f(facts['kappaWeighted'], '{:.2f}')}.",
        f"- Price is known for {f(facts['priceCoverage'], '{:.1f}')}% of phones; null specs "
        "never satisfy a filter.",
        "",
        "## Baselines and tuning",
        "",
    ]
    if t:
        L.append(
            f"- Best BM25 on dev: k1 = {t['best']['k1']:g}, b = {t['best']['b']:g}, "
            f"{t['objective']} = {t['best'][t['objective']]:.3f} (default: "
            f"{f((t.get('default') or {}).get(t['objective']))}). Table `tab:bm25-tuning`, "
            "Figure `bm25_tuning_heatmap`."
        )
    else:
        L.append("- BM25 tuning: pending.")
    sig = ((abl.get("significance") or {}).get("test") or {}).get("nDCG@10", {})
    for base, label in (("tfidf_lnc.ltc", "TF-IDF"), ("bm25_default", "BM25 default")):
        if base in sig:
            r = sig[base]
            L.append(
                f"- BM25 tuned vs. {label} (test nDCG@10): diff {-r['mean_diff']:+.3f}, "
                f"p_Holm = {r['p_randomization_holm']:.4f}."
            )
    L += ["", "## Structure: filters and phrases", ""]
    inc = (abl.get("incremental") or {}).get("test", [])
    for e_ in inc:
        if e_["label"].startswith("+") and e_["status"] == "ok":
            L.append(
                f"- {e_['label']} vs. {e_['parent']}: delta nDCG@10 {e_['delta']:+.3f}, "
                f"p = {e_['p']:.4f}, W/L/T {e_['wins']}/{e_['losses']}/{e_['ties']}."
            )
    if sub:
        for run, r in sub["runs"].items():
            w, wo = r["with_constraints"], r["without_constraints"]
            L.append(
                f"- {run}: nDCG@10 {f(w['nDCG@10'])} on {w['n']} constrained queries vs. "
                f"{f(wo['nDCG@10'])} on {wo['n']} unconstrained (Table `tab:filters-subset`)."
            )
    else:
        L.append("- Constraint-subset analysis: pending.")
    L += ["", "## Neural and fusion", ""]
    for e_ in inc:
        if e_["owner"] == "B":
            L.append(
                f"- {e_['label']}: "
                + (
                    f"delta nDCG@10 vs. {e_['parent']} {e_['delta']:+.3f}, p = {e_['p']:.4f}"
                    if e_["status"] == "ok"
                    else "pending (B)"
                )
                + "."
            )
    L += [
        "",
        "## Ablation",
        "",
        "- Table `tab:ablation-test` (results/ablation_test.tex); appendix "
        "`tab:ablation-dev`; Table `tab:ablation-incremental-test`.",
        "- Figures: ablation_bars (95% bootstrap CIs), pr_key_systems, delta_best_vs_bm25.",
        f"- Best overall (chosen on dev nDCG@10): {facts['bestSystem'] or 'pending'}; dev "
        f"{f(facts['bestSystemDevNDCG'])}, test {f(facts['bestSystemNDCG'])}, vs. BM25 tuned "
        f"{f(facts['bestVsBMDelta'], '{:+.3f}')}.",
    ]
    low = [r["label"] for r in (abl.get("rows") or {}).get("test", []) if r.get("low_coverage")]
    if low:
        L.append(f"- judged@10 < 0.7 (scores are lower bounds): {', '.join(low)}.")
    pend = abl.get("pending") or []
    if pend:
        L.append("- Pending rows: " + ", ".join(f"{p['label']} ({p['owner']})" for p in pend) + ".")
    L += ["", "## Efficiency", ""]
    if e:
        L.append(
            f"- Boolean AND over {e['n_queries']} random 2-3 term queries: skip pointers "
            f"cut comparisons by {100 * e['comparison_reduction']:.0f}% "
            f"({e['without_skips']['mean_comparisons']:.0f} -> "
            f"{e['with_skips']['mean_comparisons']:.0f}); mean latency "
            f"{e['without_skips']['mean_us']:.1f} -> {e['with_skips']['mean_us']:.1f} us "
            f"({e['speedup_mean_latency']:.2f}x). Table `tab:efficiency`."
        )
    for p in sorted(res.glob("latency_*.json")):
        d = load(p)
        L.append(f"- {d['run']}: mean {d['mean_ms']:.2f} ms, p95 {d['p95_ms']:.2f} ms per query.")
    L += [
        "",
        "## Failure analysis",
        "",
        "- results/failure_cases.md: 3 lowest-nDCG@10 test queries of the best system and "
        "the 2 largest losses vs. BM25 tuned (fill in the Why: lines).",
        "",
    ]
    return "\n".join(L)


def update_readme(res: Path, readme: Path) -> bool:
    text = readme.read_text(encoding="utf-8")
    m = re.search(
        r"(<!-- BEGIN results-summary -->\n)(.*?)(<!-- END results-summary -->)", text, re.DOTALL
    )
    if not m:
        return False
    src = res / "ablation_test.md"
    body = src.read_text(encoding="utf-8") if src.exists() else "Pending: run `make ablation`.\n"
    body = (
        "Generated from `results/ablation_test.md` by `scripts/report_numbers.py`; do not "
        "edit by hand.\n\n" + body
    )
    readme.write_text(
        text[: m.start(2)] + body + "\n" + text[m.end(2) :], encoding="utf-8", newline="\n"
    )
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--results-dir", type=Path)
    ap.add_argument("--out-dir", type=Path)
    ap.add_argument("--no-readme", action="store_true")
    args = ap.parse_args(argv)
    res = args.results_dir or get_path("results_dir")
    out = args.out_dir or repo_root() / "report" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    mac, facts = macros(res)
    files = {
        "dataset_stats.tex": dataset_stats(res),
        "index_stats.tex": index_stats(res),
        "efficiency.tex": efficiency(res),
        "bm25_tuning.tex": bm25_tuning(res),
        "filters_subset.tex": filters_subset(res),
        "numbers.tex": mac,
        "experiments_retrieval_skeleton.md": skeleton(res, facts),
    }
    for name, content in files.items():
        (out / name).write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files to {out}")
    pend = [k for k, v in facts.items() if v is None]
    if pend:
        print("pending macros: " + ", ".join(pend))
    if not args.no_readme:
        print(
            "README results summary "
            + (
                "updated"
                if update_readme(res, repo_root() / "README.md")
                else "markers not found (skipped)"
            )
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
